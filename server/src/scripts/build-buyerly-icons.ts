function paths(pack: string, name: string, weight: string): string[] {
  const suffix = weight === 'regular' ? '' : `-${weight}`;
  const svg = readFileSync(path.join(pack, 'assets', weight, `${name}${suffix}.svg`), 'utf8');
  const body = svg.trim().replace(/^<svg[^>]*>|<\/svg>\s*$/g, '');
  const found = [...body.matchAll(/<path d="([^"]+)"\s*\/>/g)].map((match) => match[1]);
  if (found.length === 0 || body.replace(/<path d="[^"]+"\s*\/>/g, '').trim()) {
    throw new Error(`${name}-${weight}: only <path d> elements are supported`);
  }
  return found;
}

