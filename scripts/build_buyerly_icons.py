def paths(package: Path, name: str, weight: str) -> list[str]:
    suffix = '' if weight == 'regular' else f'-{weight}'
    svg = (package / 'assets' / weight / f'{name}{suffix}.svg').read_text()
    body = re.sub(r'^<svg[^>]*>|</svg>\s*$', '', svg.strip())
    found = re.findall(r'<path d="([^"]+)"\s*/>', body)
    if not found or re.sub(r'<path d="[^"]+"\s*/>', '', body).strip():
        raise SystemExit(f'{name}-{weight}: only <path d> elements are supported')
    return found


def main() -> None:
    package = Path(sys.argv[1])
    version = re.search(r'"version":\s*"([^"]+)"', (package / 'package.json').read_text()).group(1)
    out = Path(__file__).resolve().parent.parent / 'frontend/src/icons/buyerlyIconPaths.ts'
    lines = [
        f'// Generated by scripts/build_buyerly_icons.py from @phosphor-icons/core {version}.',
        '// Phosphor Icons, MIT License, Copyright (c) 2023 Phosphor Icons. Do not edit by hand.',
        '',
        'export const BUYERLY_ICON_PATHS = {',
    ]
    for role, source in ROLES.items():
        name, weight = source if isinstance(source, tuple) else (source, 'bold')
        ds = ', '.join(f"'{d}'" for d in paths(package, name, weight))
        lines.append(f"  '{role}': [{ds}],")
    lines += ['} as const;', '', 'export type BuyerlyIconName = keyof typeof BUYERLY_ICON_PATHS;', '']
    out.write_text('\n'.join(lines))
    print(f'{out}: {len(ROLES)} icons')


if __name__ == '__main__':
    main()
